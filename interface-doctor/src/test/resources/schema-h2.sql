-- 接口注册表：启动自检（RegisteredRouteCatalog）要与它对账——**故意保留这张表**，
-- 因为"注册表说有哪些接口"与"代码里实现了哪些接口"必须一致，测试里也要跑同一条对账逻辑。
-- param_schema 的 properties 必须与各接口的入参 record 字段逐一对上，否则接口服务拒绝启动。
CREATE TABLE sys_api (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(128) NOT NULL,
    service      VARCHAR(64)  NOT NULL,
    http_method  VARCHAR(8)   NOT NULL,
    http_path    VARCHAR(255) NOT NULL,
    kind         VARCHAR(8)   NOT NULL DEFAULT 'read',
    resource     VARCHAR(128),
    param_schema VARCHAR(4000),
    scenario     VARCHAR(2000),
    result_schema VARCHAR(4000),
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE
);

