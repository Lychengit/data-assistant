-- 接口服务测试 schema：只建业务表与 I6 审计表。
-- 故意**没有** sys_user / sys_role / role_api 等权限表——接口服务不查权限库、不重算范围（§20.1.6-6）；
-- 若有人在这里塞进权限查询，这个 schema 会立刻让它跑不起来（这正是我们要的护栏）。

CREATE TABLE doctor_metric (
    doctor_id    VARCHAR(64) NOT NULL,
    doctor_name  VARCHAR(64),
    dept_code    VARCHAR(64) NOT NULL,
    stat_month   VARCHAR(7)  NOT NULL,
    metric_key   VARCHAR(64) NOT NULL,
    metric_value NUMERIC(18, 2)
);

