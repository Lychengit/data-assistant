-- V10：LLM 供应商配置（ADR-14 / §20.1.6）。
-- H2 没有部分唯一索引，「同一时刻至多一个 enabled」在测试里由服务层的
-- disableOthers + 用例断言保证；PG 侧另有 ux_sys_llm_provider_enabled 兜底。
-- created_at / updated_at 给 CURRENT_TIMESTAMP 默认值：生产 SQL 靠 now() 默认值，
-- 测试库必须同样能「不给时间戳也插得进去」，否则测的就不是同一套 SQL 语义。
CREATE TABLE sys_llm_provider (
    provider_id    VARCHAR(64)   PRIMARY KEY,
    adapter        VARCHAR(32)   NOT NULL,
    base_url       VARCHAR(255)  NOT NULL,
    model          VARCHAR(128)  NOT NULL,
    api_key_cipher VARCHAR(1000) NOT NULL,
    key_hint       VARCHAR(64)   NOT NULL,
    enabled        BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
