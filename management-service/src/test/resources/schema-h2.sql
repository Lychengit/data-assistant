-- 管理后台测试 schema：账号 / 角色 / 接口注册 / 授权 / 配置审计 / 刷新令牌。
-- 与 deploy/migrations/V1–V4 的列名对齐（jsonb → VARCHAR，PG 侧读到的是同一份 JSON 文本）。

CREATE TABLE sys_user (
    id            BIGINT PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'active'
);

CREATE TABLE sys_role (
    id        BIGINT PRIMARY KEY,
    role_code VARCHAR(64) NOT NULL UNIQUE
);

CREATE TABLE sys_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE sys_skill (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_code   VARCHAR(64)  NOT NULL UNIQUE,
    name         VARCHAR(128) NOT NULL DEFAULT '',
    description  VARCHAR(4000),
    owner_type   VARCHAR(16)  NOT NULL DEFAULT 'platform',
    owner_id     BIGINT,
    read_only    BOOLEAN      NOT NULL DEFAULT TRUE,
    param_schema VARCHAR(4000),
    status       VARCHAR(16)  NOT NULL DEFAULT 'draft',
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE role_skill (
    role_id  BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    can_view BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (role_id, skill_id)
);

CREATE TABLE skill_api (
    skill_id    BIGINT      NOT NULL,
    api_id      BIGINT      NOT NULL,
    approved    BOOLEAN     NOT NULL DEFAULT FALSE,
    approved_by VARCHAR(64),
    approved_at TIMESTAMP,
    PRIMARY KEY (skill_id, api_id)
);

CREATE TABLE sys_api (
    -- 起始值避开下面演示种子的显式 id（1 / 2），等价于 PG 侧的 BIGSERIAL
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 100) PRIMARY KEY,
    name     VARCHAR(128) NOT NULL,
    service  VARCHAR(64)  NOT NULL,
    http_method VARCHAR(8)   NOT NULL,
    http_path   VARCHAR(255) NOT NULL,
    kind        VARCHAR(8)   NOT NULL DEFAULT 'read',
    resource VARCHAR(128),
    param_schema     VARCHAR(4000),
    scenario         VARCHAR(2000),
    result_schema    VARCHAR(4000),
    enabled  BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP
);

-- 口径字典（§6.1 / V5 规格字段）。
CREATE TABLE metric_dictionary (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_key VARCHAR(64)  NOT NULL UNIQUE,
    domain     VARCHAR(64),
    name       VARCHAR(128) NOT NULL,
    aliases    VARCHAR(4000),
    definition VARCHAR(4000),
    formula    VARCHAR(4000),
    time_basis VARCHAR(32),
    unit       VARCHAR(32),
    scale      NUMERIC(18, 6),
    rounding   INT NOT NULL DEFAULT 1,
    derived_of VARCHAR(4000),
    timezone   VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    basis      VARCHAR(4000),
    enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP
);

CREATE TABLE unit_convert (
    from_unit VARCHAR(32)    NOT NULL,
    to_unit   VARCHAR(32)    NOT NULL,
    factor    NUMERIC(18, 6) NOT NULL,
    PRIMARY KEY (from_unit, to_unit)
);

-- 审计四件事：判定 / 数据访问 / 审计读（配置变更见 config_audit）。
CREATE TABLE permission_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id       VARCHAR(64) NOT NULL,
    user_id        VARCHAR(64),
    role_ids       VARCHAR(4000),
    tool_name      VARCHAR(128),
    decision       VARCHAR(16) NOT NULL,
    reason         VARCHAR(255),
    scope_snapshot VARCHAR(4000),
    created_at     TIMESTAMP NOT NULL
);

CREATE TABLE data_access_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id     VARCHAR(64) NOT NULL,
    trace_id       VARCHAR(64),
    caller_key_id  VARCHAR(64),
    user_id        VARCHAR(64) NOT NULL,
    service        VARCHAR(64),
    http_method    VARCHAR(8),
    http_path      VARCHAR(255),
    skill_code     VARCHAR(64),
    scope_snapshot VARCHAR(4000),
    outcome        VARCHAR(24) NOT NULL,
    reason         VARCHAR(255),
    row_count      INT,
    truncated      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP NOT NULL
);

CREATE TABLE audit_read_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    who        VARCHAR(64) NOT NULL,
    action     VARCHAR(64) NOT NULL,
    params     VARCHAR(4000),
    outcome    VARCHAR(16) NOT NULL,
    row_count  INT,
    reason     VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

-- 编排侧事实表（回放用，§8.3）。
CREATE TABLE conversation_turn (
